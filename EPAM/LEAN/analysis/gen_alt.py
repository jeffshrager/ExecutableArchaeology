#!/usr/bin/env python3
"""Generate ../Epam/Fig41Alt.lean from codes_fig41.txt: letter codes that keep
every bit U1 tests (so each still sorts to its own letter in EPAM II's letter
net) and fill the untested bits so that all 34 of Fig. 4.1's recorded
responses are possible. (Found by robustness.py's sampler, seed 7.)
Run from EPAM/LEAN/analysis: python3 gen_alt.py"""
rows = [l.split() for l in open('codes_fig41.txt')]


def lit(bits):
    return '[' + ', '.join('true' if b == '1' else 'false' for b in bits) + ']'


out = ['''/-
P-1817 Fig. 4.1 under other letter codes consistent with U1.

Generated by `analysis/gen_alt.py` from `analysis/codes_fig41.txt`. These codes
keep every bit that EPAM II's letter net U1 tests on each letter's path (so
each letter still sorts to its own terminal; `alt_respects_U1`), and A keeps
its historical code. The untested bits are filled so that **all 34** of
Feigenbaum's recorded responses are possible under the postulates
(`alt_agreement`). In random sampling (robustness.py), about 10% of
U1-consistent completions do this under the figure's assumptions.

Under these codes KAG's cue for LUK is precarious, as note 12 says: KAG can
fail on trial 6, and so its correct response on trial 7 is possible but not
certain (`alt_trial7_KAG_by_chance`).
-/

import Epam.Fig41

namespace Epam.Fig41Alt

open Epam Fig41 SylSet
''']
for L, bits, fixed in rows:
    out.append('/-- %s: U1 fixes `%s`. -/\ndef %s : Item := %s' % (L, fixed, L, lit(bits)))
    out.append('def %sFixed : List (Nat × Bool) := %s' % (
        L, '[' + ', '.join('(%d, %s)' % (i, 'true' if c == '1' else 'false')
                            for i, c in enumerate(fixed) if c != '.') + ']'))
letters = [r[0] for r in rows]
out.append('''
/-- Every bit U1 tests has the value U1 requires. -/
theorem alt_respects_U1 :
''' + ' ∧\n'.join('    (%sFixed.all fun p => %s.feat p.1 == p.2)' % (L, L) for L in letters) + ''' = true := by
  decide

def alt : SylSet := ⟨K ++ A ++ G, L ++ U ++ K, R ++ I ++ L, P ++ E ++ M, R ++ O ++ M, T ++ I ++ L⟩

/-- **All 34 of Fig. 4.1's recorded responses are possible.** -/
theorem alt_agreement : ((fig alt).filter (agrees alt)).length = 34 := by decide

/-- Note 7 holds here too: PEM can only give ROM's response, TIL. -/
theorem alt_trial4_PEM : responsesAt alt 4 3 = [some alt.TIL] := by decide

/-- Note 12: KAG's link is precarious. On trial 6 it can fail; on trial 7 the
correct response is possible but not certain. -/
theorem alt_trial7_KAG_by_chance :
    (responsesAt alt 6 0).contains none ∧
      (responsesAt alt 7 0).contains (some alt.LUK) ∧ (responsesAt alt 7 0).contains none := by
  decide

end Epam.Fig41Alt
''')
open('../Epam/Fig41Alt.lean', 'w').write('\n'.join(out))
print('wrote ../Epam/Fig41Alt.lean')
